// Run after a STATIC_EXPORT build. Adds the files that Next.js would otherwise provide at runtime:
// .htaccess (security headers, caching, redirects), the Bee HQ tracker script and its PHP beacon proxy.
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

if (!existsSync('out')) throw new Error('out/ not found: run "npm run build:static" first');
const cfg = readFileSync('next.config.ts', 'utf8');
const csp = eval(cfg.match(/const csp = (\[[\s\S]*?\])\.join/)[1]).join('; ');
const hq = (process.env.BEEHQ_ORIGIN || 'https://hq.beechargedev.com').replace(/\/$/, '');

const htaccess = `# Generated by scripts/static-extras.mjs. Do not edit on the server.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On
# /index.html and /section/index.html -> clean URL
RewriteCond %{THE_REQUEST} \\s/+(.*?)index\\.html[\\s?] [NC]
RewriteRule ^ /%1 [R=301,L]
# Removed pages: tell crawlers they are gone for good (410)
# Tracker beacon -> PHP proxy
RewriteRule ^api/t/?$ /_a/proxy.php [L]
</IfModule>

<IfModule mod_headers.c>
Header always set Content-Security-Policy "${csp}"
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=()"
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml text/plain application/xml
</IfModule>
`;
const immutable = `<IfModule mod_headers.c>\nHeader set Cache-Control "public, max-age=31536000, immutable"\n</IfModule>\n`;
const proxy = `<?php
// Forwards the dashboard beacon to Bee HQ so the browser only talks to this domain.
$hq = '${hq}/api/t';
if ($_SERVER['REQUEST_METHOD'] !== 'POST') { http_response_code(204); exit; }
$body = file_get_contents('php://input', false, null, 0, 2048);
$ip = $_SERVER['HTTP_X_FORWARDED_FOR'] ?? $_SERVER['REMOTE_ADDR'] ?? '';
$headers = ['Content-Type: text/plain', 'User-Agent: ' . ($_SERVER['HTTP_USER_AGENT'] ?? ''), 'X-Forwarded-For: ' . $ip, 'Referer: ' . ($_SERVER['HTTP_REFERER'] ?? '')];
if (function_exists('curl_init')) {
  $c = curl_init($hq);
  curl_setopt_array($c, [CURLOPT_POST => true, CURLOPT_POSTFIELDS => $body, CURLOPT_HTTPHEADER => $headers, CURLOPT_RETURNTRANSFER => true, CURLOPT_TIMEOUT => 3]);
  curl_exec($c); curl_close($c);
} else {
  @file_get_contents($hq, false, stream_context_create(['http' => ['method' => 'POST', 'header' => implode("\\r\\n", $headers), 'content' => $body, 'timeout' => 3]]));
}
http_response_code(204);
`;
writeFileSync('out/.htaccess', htaccess);
for (const d of ['out/_next/static', 'out/images']) if (existsSync(d)) writeFileSync(`${d}/.htaccess`, immutable);
mkdirSync('out/_a', { recursive: true });
cpSync('static/_a/t.js', 'out/_a/t.js');
writeFileSync('out/_a/proxy.php', proxy);
console.log('Static extras written to out/ (.htaccess, _a/t.js, _a/proxy.php)');
